//! The addon's settings: their schema (addon/settings.json, also read by the app's Addon page) and
//! the Config.lua the app writes from the player's choices.

use anyhow::Result;
use serde::Deserialize;
use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::path::Path;

/// Every setting of the addon, grouped as the app shows them, and the app's setup questions.
const SCHEMA: &str = include_str!("../../../../addon/settings.json");

#[derive(Deserialize)]
struct Schema {
    groups: Vec<Group>,
}

#[derive(Deserialize)]
struct Group {
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "a comment of the addon's defaults, checked in tests")
    )]
    title: String,
    sections: Vec<Section>,
}

#[derive(Deserialize)]
struct Section {
    options: Vec<Setting>,
}

#[derive(Deserialize)]
struct Setting {
    key: String,
    default: Value,
    min: Option<f64>,
    max: Option<f64>,
    /// A select's values.
    #[serde(default)]
    options: Vec<Choice>,
}

#[derive(Deserialize)]
struct Choice {
    value: String,
}

fn schema() -> Schema {
    serde_json::from_str(SCHEMA).expect("addon/settings.json is valid")
}

impl Setting {
    /// `value` when it fits the setting (same type, a select's value, a number within bounds,
    /// brought within them), otherwise the default.
    fn checked(&self, value: Option<&Value>) -> Value {
        match (value, &self.default) {
            (Some(v @ Value::Bool(_)), Value::Bool(_)) => v.clone(),
            (Some(Value::String(s)), Value::String(_)) if self.options.iter().any(|c| c.value == *s) => {
                Value::String(s.clone())
            }
            (Some(Value::Number(n)), Value::Number(_)) => {
                let Some(mut x) = n.as_f64() else {
                    return self.default.clone();
                };
                if let Some(min) = self.min {
                    x = x.max(min);
                }
                if let Some(max) = self.max {
                    x = x.min(max);
                }
                if x.fract() == 0.0 && x.abs() < 1e15 {
                    #[expect(clippy::cast_possible_truncation, reason = "a whole number in i64's range")]
                    return Value::from(x as i64);
                }
                serde_json::Number::from_f64(x).map_or_else(|| self.default.clone(), Value::Number)
            }
            _ => self.default.clone(),
        }
    }
}

fn lua_value(value: &Value) -> String {
    match value {
        Value::String(s) => format!("{s:?}"),
        v => v.to_string(),
    }
}

/// Write the addon's Config.lua: every setting of the schema with the player's value (from the
/// app's settings, flat key -> bool/number/string) or its default, and the guides' language.
pub fn write_addon_config(addon_dir: &Path, values: &Map<String, Value>, locale: Option<&str>) -> Result<()> {
    let mut out =
        String::from("-- Generated by the Factoruide app. Do not edit.\nlocal FG = Factoruide\nFG.Config = {\n");
    for group in schema().groups {
        for setting in group.sections.iter().flat_map(|s| &s.options) {
            let _ = writeln!(
                out,
                "    {} = {},",
                setting.key,
                lua_value(&setting.checked(values.get(&setting.key)))
            );
        }
    }
    if let Some(locale) = locale {
        let _ = writeln!(out, "    locale = {locale:?},");
    }
    out.push_str("}\n");
    std::fs::write(addon_dir.join("Config.lua"), out)?;
    Ok(())
}

/// The defaults and number bounds of the settings, as written in the addon's Settings.lua.
#[cfg(test)]
fn defaults_lua() -> String {
    let mut defaults = String::from("FG.defaults = {\n");
    let mut bounds = String::from("-- The bounds of the numbers.\nFG.bounds = {\n");
    for group in schema().groups {
        let _ = writeln!(defaults, "    -- {}", group.title);
        for setting in group.sections.iter().flat_map(|s| &s.options) {
            let _ = writeln!(defaults, "    {} = {},", setting.key, lua_value(&setting.default));
            if let (Some(min), Some(max)) = (setting.min, setting.max) {
                let _ = writeln!(bounds, "    {} = {{ {min}, {max} }},", setting.key);
            }
        }
    }
    format!("{defaults}}}\n{bounds}}}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    const BEGIN: &str = "-- BEGIN addon/settings.json\n";
    const END: &str = "-- END addon/settings.json\n";

    /// The addon's defaults are those of the schema. `FG_WRITE_SETTINGS=1 cargo test -p fg-route
    /// addon_settings` writes them again after a change of addon/settings.json.
    #[test]
    fn addon_defaults_follow_the_schema() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../addon/Factoruide_Guide/Settings.lua");
        let lua = std::fs::read_to_string(&path).unwrap();
        let start = lua.find(BEGIN).expect("generated block start") + BEGIN.len();
        let end = lua.find(END).expect("generated block end");
        let generated = defaults_lua();
        if lua[start..end] == generated {
            return;
        }
        if std::env::var_os("FG_WRITE_SETTINGS").is_some() {
            std::fs::write(&path, format!("{}{generated}{}", &lua[..start], &lua[end..])).unwrap();
            return;
        }
        panic!("Settings.lua's defaults differ from addon/settings.json: run with FG_WRITE_SETTINGS=1");
    }

    #[test]
    fn config_keeps_valid_values_and_defaults_the_rest() {
        let dir = std::env::temp_dir().join(format!("fg-addon-config-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let values = serde_json::json!({
            "autoAccept": false,
            "guideMode": "minimal",
            "uiTheme": "purple",
            "scale": 9,
            "trackerQuests": "many",
            "removedSetting": true,
        });
        write_addon_config(&dir, values.as_object().unwrap(), Some("frFR")).unwrap();
        let lua = std::fs::read_to_string(dir.join("Config.lua")).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
        for line in [
            "autoAccept = false,",
            "guideMode = \"minimal\",",
            "uiTheme = \"dark\",",
            "scale = 2,",
            "trackerQuests = 8,",
            "autoTurnIn = true,",
            "locale = \"frFR\",",
        ] {
            assert!(lua.contains(line), "{line} missing in\n{lua}");
        }
        assert!(!lua.contains("removedSetting"));
    }

    #[test]
    fn setup_answers_name_settings_and_default_ones_keep_the_defaults() {
        let raw: Value = serde_json::from_str(SCHEMA).unwrap();
        let defaults: Map<String, Value> = schema()
            .groups
            .into_iter()
            .flat_map(|g| g.sections)
            .flat_map(|s| s.options)
            .map(|s| (s.key, s.default))
            .collect();
        for step in raw["wizard"].as_array().unwrap() {
            for question in step["questions"].as_array().unwrap() {
                let choices = question["choices"].as_array().unwrap();
                assert_eq!(
                    choices.iter().filter(|c| c["default"] == true).count(),
                    1,
                    "one default answer to {}",
                    question["label"]
                );
                for choice in choices {
                    for (key, value) in choice["values"].as_object().unwrap() {
                        let default = defaults
                            .get(key)
                            .unwrap_or_else(|| panic!("{key} of the setup is not a setting"));
                        // Taking every default answer leaves the settings as they are.
                        if choice["default"] == true {
                            assert_eq!(value, default, "{key} of the default answer to {}", question["label"]);
                        }
                    }
                }
            }
        }
    }
}
